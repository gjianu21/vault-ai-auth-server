#!/bin/bash
# Runs once, on the first container start, as SYSDBA.
# Creates one schema per service in the FREEPDB1 pluggable database.
set -e

sqlplus -s / as sysdba <<EOF
WHENEVER SQLERROR EXIT SQL.SQLCODE
ALTER SESSION SET CONTAINER = FREEPDB1;

CREATE USER VAULT_AUTH IDENTIFIED BY "${VAULT_AUTH_DB_PASSWORD}"
    DEFAULT TABLESPACE USERS QUOTA UNLIMITED ON USERS;
GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE, CREATE VIEW TO VAULT_AUTH;

CREATE USER VAULT_APP IDENTIFIED BY "${VAULT_APP_DB_PASSWORD}"
    DEFAULT TABLESPACE USERS QUOTA UNLIMITED ON USERS;
GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE, CREATE VIEW TO VAULT_APP;

EXIT;
EOF

echo "Vault AI schemas created: VAULT_AUTH, VAULT_APP"